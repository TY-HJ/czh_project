/**
 * 取某报修类型的完工勾选项
 * @param {string} typeName
 * @returns {{causes:string[], actions:string[], checks:string[]}}
 */
export function getFinishOptions(typeName) {
  return FINISH_LIB[groupOf(typeName)] || FINISH_LIB.其他
}

/**
 * 把勾选项拼成一句处理说明
 * @param {{causes?:string[], actions?:string[], checks?:string[]}} sel
 * @returns {string} 如「经检查，故障原因为阀芯老化；已更换配件、紧固接线；已通水测试无渗漏，已清理现场。」
 */
export function buildFinishNote(sel) {
  const causes = (sel && sel.causes) || []
  const actions = (sel && sel.actions) || []
  const checks = (sel && sel.checks) || []
  const parts = []
  if (causes.length) parts.push('经检查，故障原因为' + causes.join('、'))
  if (actions.length) parts.push('已' + actions.join('、'))
  if (checks.length) parts.push(checks.join('，'))
  return parts.length ? parts.join('；') + '。' : ''
}
