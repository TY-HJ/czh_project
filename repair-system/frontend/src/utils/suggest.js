/** 按类型名归组：先判「电梯」「门禁」，再判「门窗」，避免「电梯」被「电」误伤 */
function groupOf(typeName) {
  const n = String(typeName || '')
  if (n.includes('电梯')) return '电梯故障'
  if (n.includes('门禁')) return '门禁系统'
  if (n.includes('门窗')) return '门窗维修'
  if (n.includes('照明') || n.includes('灯')) return '公共照明'
  if (n.includes('网络') || n.includes('网')) return '网络故障'
  if (n.includes('水') || n.includes('电')) return '水电维修'
  return '其他'
}

